def _parse(raw: str) -> List[List[int]]:
    rows = [line for line in raw.splitlines() if line != ""]
    grid = []
    for row in rows:
        grid.append([1 if ch == "#" else 0 for ch in row.ljust(GLYPH_WIDTH)])
    return grid


FONT_5x7: Dict[str, List[List[int]]] = {ch: _parse(raw) for ch, raw in _RAW.items()}

BLANK_GLYPH: List[List[int]] = [[0] * GLYPH_WIDTH for _ in range(GLYPH_HEIGHT)]


def glyph(char: str) -> List[List[int]]:
    """Return the 7x5 pixel grid for a character (blank if unknown)."""
    return FONT_5x7.get(char.upper(), BLANK_GLYPH)
